const STORAGE_LANG = 'atmos_lang_v1';

export function loadSavedLang() {
  try {
    const v = localStorage.getItem(STORAGE_LANG);
    return v === 'en' ? 'en' : 'id';
  } catch {
    return 'id';
  }
}

export function saveLang(lang) {
  try {
    localStorage.setItem(STORAGE_LANG, lang);
  } catch {
    // ignore
  }
}

